import assert from "node:assert/strict";
import {scheduleDates,rowFromDates,hoursForSchedule} from "../lib/activity-calendar.ts";
const initial={week:"2026-V40",day:"Måndag",duration:"10 veckor"};
const old=scheduleDates(initial);
assert.equal(old.start,"2026-09-28");
assert.equal(old.end,"2026-12-06");
const moved={...initial,week:"2026-V41",day:"Tisdag"};
const later=scheduleDates(moved);
assert.equal(later.start,"2026-10-06");
assert.equal(later.end,"2026-12-14");
assert.equal(Date.parse(later.end)-Date.parse(old.end),Date.parse(later.start)-Date.parse(old.start));
assert.deepEqual(rowFromDates(old.start,old.end),initial);
assert.deepEqual(rowFromDates(later.start,later.end),moved);
const extended=scheduleDates({...initial,duration:"12 veckor"});
assert.equal(extended.start,old.start);
assert.equal(extended.end,"2026-12-20");
const shortened=scheduleDates({...initial,duration:"5 veckor"});
assert.equal(shortened.start,old.start);
assert.equal(shortened.end,"2026-11-01");
const year=scheduleDates({week:"2026-V53",day:"Torsdag",duration:"10 veckor"});
assert.equal(year.start,"2026-12-31");
assert.deepEqual(rowFromDates(year.start,year.end),{week:"2026-V53",day:"Torsdag",duration:"10 veckor"});
assert.equal(hoursForSchedule({...initial,effort:50}),200);
console.log("PASS activity schedule: one row, moved start, fixed duration, extended end and year rollover");
